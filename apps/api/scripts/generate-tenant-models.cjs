#!/usr/bin/env node
/* Generates src/common/prisma/tenant-models.generated.ts from prisma/schema.prisma.
   A model is tenant-scoped when it has a `workspaceId` field. Run: pnpm --filter api generate:tenant-models */
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SCHEMA = path.join(ROOT, 'prisma', 'schema.prisma');
const OUTPUT = path.join(ROOT, 'src', 'common', 'prisma', 'tenant-models.generated.ts');

/** Minimal Prisma schema reader: model names with their field lines and block attributes. */
function parseModels(source) {
  const models = [];
  const blockPattern = /^model\s+(\w+)\s*\{([\s\S]*?)^\}/gm;
  let match;
  while ((match = blockPattern.exec(source)) !== null) {
    const lines = match[2]
      .split('\n')
      .map((l) => l.replace(/\/\/.*$/, '').trim())
      .filter(Boolean);
    const fields = lines
      .filter((l) => !l.startsWith('@@'))
      .map((l) => ({ name: l.split(/\s+/)[0], line: l }));
    const attributes = lines.filter((l) => l.startsWith('@@'));
    models.push({ name: match[1], fields, attributes });
  }
  return models;
}

/** Tenant-scoped means a REQUIRED workspaceId; UserSession's optional one is only a pointer. */
function isTenantModel(model) {
  return model.fields.some(
    (f) => f.name === 'workspaceId' && /^workspaceId\s+String(\s|$)/.test(f.line),
  );
}

function render(models) {
  const tenant = models.filter(isTenantModel).map((m) => m.name);
  const all = models.map((m) => m.name);
  const list = (names) =>
    names.length ? `[\n${names.map((n) => `  '${n}',`).join('\n')}\n]` : '[]';
  return [
    '// GENERATED by scripts/generate-tenant-models.cjs from prisma/schema.prisma. Do not edit.',
    '',
    `export const ALL_MODEL_NAMES: readonly string[] = ${list(all)};`,
    '',
    `export const TENANT_MODEL_NAMES: readonly string[] = ${list(tenant)};`,
    '',
  ].join('\n');
}

function generate() {
  return render(parseModels(fs.readFileSync(SCHEMA, 'utf8')));
}

module.exports = { parseModels, isTenantModel, render, generate, SCHEMA, OUTPUT };

if (require.main === module) {
  fs.writeFileSync(OUTPUT, generate());
  console.log(`wrote ${path.relative(ROOT, OUTPUT)}`);
}
